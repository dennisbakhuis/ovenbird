@pytest.mark.parametrize("module", sorted(OLD_NAMES))
def test_every_former_name_still_resolves(module: str) -> None:
    """Each public name of a moved module is importable from its former path."""
    loaded = importlib.import_module(module)
    missing = [name for name in OLD_NAMES[module] if not hasattr(loaded, name)]
    assert missing == []


def test_the_former_trial_router_builder_resolves() -> None:
    """The former router module still offers its builder."""
    from ovenbird.api.trial_api import build_trial_router

    assert callable(build_trial_router)
